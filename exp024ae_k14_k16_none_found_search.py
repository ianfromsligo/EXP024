def test_k16_predictions():
    """
    Test k=16 predictions:
    - k=8 has some solutions (ρ=1/2 with δ=0,π/2,π,3π/2)
    - Does k=16 inherit from k=8? The doubling property only applies from odd k
    - k=8 is even, so likely NO inheritance
    - But k=16 might have its own fundamental solutions?
    """
    print("\n" + "=" * 80)
    print("TESTING k=16 PREDICTIONS")
    print("k=8 has ρ=1/2 solutions. Does k=16 inherit? (Probably NOT)")
    print("=" * 80)

    # Test inheritance from k=8 solutions
    k8_solutions = [
        (1/2, 0),
        (1/2, np.pi/2),
        (1/2, np.pi),
        (1/2, 3*np.pi/2),
    ]

    print("\nTesting inheritance from k=8 solutions:")
    inheritance_found = False

    for rho, delta in k8_solutions:
        rho_val = float(rho)
        # Try N values that worked for k=8
        for N in [8, 16, 24, 32, 40, 48, 56, 64]:
            result = verify_revival(16, rho_val, delta, N)
            if result['is_identity']:
                print(f"  ✓ INHERITED! N={N}, ρ={rho_val}, δ={np.degrees(delta):.0f}°")
                inheritance_found = True
                break
        else:
            print(f"  ✗ No inheritance: ρ={rho_val}, δ={np.degrees(delta):.0f}°")

    if not inheritance_found:
        print("\n  → No inheritance from k=8 (as expected, since 8 is even)")

    # Search for potential new k=16 fundamental solutions
    print("\nSearching for potential fundamental k=16 solutions (0<ρ<1):")

    # Special δ values that might work for k=16 (powers of 2 often have structure)
    delta_values = [0, np.pi/4, np.pi/2, 3*np.pi/4, np.pi,
                    5*np.pi/4, 3*np.pi/2, 7*np.pi/4]

    # Candidate fractions for 4π m/n
    fractions = []
    for denom in range(1, 17):
        for num in range(1, denom):
            if np.gcd(num, denom) == 1:
                fractions.append((num, denom, 4 * np.pi * num / denom))

    found_solutions = []

    for delta in delta_values:
        cos_delta = np.cos(delta)

        for num, denom, theta in fractions:
            # Candidate ρ from l=0
            if abs(1 - cos_delta) > 1e-8:
                rho_candidate = (1 - np.cos(theta - delta)) / (1 - cos_delta)
            else:
                continue

            if 0 < rho_candidate < 1:
                # Estimate N
                delta_frac = Fraction(delta / (2 * np.pi)).limit_denominator(32)
                n_delta = delta_frac.denominator
                N_candidate = np.lcm.reduce([denom, n_delta * 2, 8])

                if N_candidate <= 128:
                    result = verify_revival(16, rho_candidate, delta, N_candidate)
                    if result['is_identity']:
                        if not (abs(rho_candidate - 0.5) < 1e-6 and delta in [0, np.pi/2, np.pi, 3*np.pi/2]):
                            found_solutions.append((N_candidate, rho_candidate, delta))
                            print(f"\n  ✨ POTENTIAL NEW! N={N_candidate}, ρ={rho_candidate:.8f}, δ={np.degrees(delta):.0f}°")
                            print(f"     Fraction: {num}/{denom}")

    if not found_solutions:
        print("\n  → No new fundamental solutions found (only ρ=1/2 from k=8 if inherited)")


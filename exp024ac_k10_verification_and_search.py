def construct_U_k(k, rho, alpha, beta):
    """Construct quantum walk operator U_k on a cycle of k nodes."""
    C = np.array([
        [np.sqrt(rho), np.sqrt(1-rho) * np.exp(1j * alpha)],
        [np.sqrt(1-rho) * np.exp(1j * beta), -np.sqrt(rho) * np.exp(1j * (alpha + beta))]
    ], dtype=complex)

    U = np.zeros((2*k, 2*k), dtype=complex)

    for i in range(k):
        for s in [0, 1]:
            if s == 0:
                new_i = (i - 1) % k
            else:
                new_i = (i + 1) % k

            old_idx = i * 2 + s
            new_idx = new_i * 2 + s
            U[new_idx, old_idx] = 1.0

    I_k = np.eye(k)
    I_kron_C = np.kron(I_k, C)
    U = U @ I_kron_C

    return U

def verify_revival(k, rho, delta, N, tol=1e-8):
    """Verify that U_k^N = I_{2k}."""
    alpha = delta
    beta = 0.0

    U = construct_U_k(k, rho, alpha, beta)
    U_power = np.linalg.matrix_power(U, N)
    I = np.eye(2*k, dtype=complex)
    diff = np.linalg.norm(U_power - I)

    eigenvalues = np.linalg.eigvals(U)
    max_eig_error = max(abs(ev**N - 1) for ev in eigenvalues)

    return {
        'diff_norm': diff,
        'is_identity': diff < tol,
        'max_eig_error': max_eig_error
    }

def verify_k10_solutions():
    """Verify k=10 solutions (inherited from k=5 with degeneracy)."""
    print("\n" + "=" * 80)
    print("VERIFYING k=10 SOLUTIONS (inherited from k=5)")
    print("=" * 80)

    rho_values = [(5 - np.sqrt(5)) / 10, (5 + np.sqrt(5)) / 10]
    delta_values = [0, 2*np.pi/5, 4*np.pi/5, 6*np.pi/5, 8*np.pi/5]

    for rho in rho_values:
        for delta in delta_values:
            # From paper: k=2η has same solutions but may have different N
            # Let's test N=60 (same as k=5) and see if smaller N works
            for N in [30, 60, 120]:
                result = verify_revival(10, rho, delta, N)
                if result['is_identity']:
                    print(f"✓ ρ={rho:.10f}, δ={delta:.4f} rad ({np.degrees(delta):.0f}°), N={N}")
                    print(f"  ||U^{N} - I|| = {result['diff_norm']:.2e}")
                    break
            else:
                print(f"✗ ρ={rho:.10f}, δ={np.degrees(delta):.0f}° - No revival found up to N=120")

def search_k10_revivals(max_denom=20, max_N=120):
    """
    Search for potential new k=10 revivals beyond the inherited k=5 solutions.
    """
    print("\n" + "=" * 80)
    print(f"SEARCHING FOR k=10 REVIVALS (max_denom={max_denom}, max_N={max_N})")
    print("=" * 80)

    # For k=10, the eigenvalue structure may allow more solutions
    # because k even gives more symmetry

    sqrt5 = np.sqrt(5)

    # For k=10, when δ = 2π·p/5 (p=0..4), we get simplifications
    delta_values = [0, 2*np.pi/5, 4*np.pi/5, 6*np.pi/5, 8*np.pi/5]

    # Also try δ = π (90° multiples) - might work for even k
    for p in [1, 2, 3]:
        delta_values.append(np.pi * p / 2)

    # Try δ = 2π·p/10 (other fractions)
    for p in range(1, 10):
        if p % 2 != 0:  # odd p gives new δ not in k=5
            delta_values.append(2 * np.pi * p / 10)

    delta_values = list(set(delta_values))  # Remove duplicates

    # Generate rational fractions
    fractions = []
    for denom in range(1, max_denom + 1):
        for num in range(1, denom):
            if np.gcd(num, denom) == 1:
                fractions.append((num, denom, 4 * np.pi * num / denom))

    print(f"Testing {len(delta_values)} δ values with {len(fractions)} fractions...")

    solutions_found = []

    for delta in delta_values:
        cos_delta = np.cos(delta)

        # For k=10, the ρ_l equations are more complex
        # We'll search systematically for rational fractions that yield consistent ρ

        for num, denom, theta in fractions:
            # Candidate ρ from one l value
            rho_candidate = 1 - np.cos(theta - delta)

            # For k=10, we need this to match across different l's
            # This is a simplified search - full search would be more comprehensive

            if 0 < rho_candidate < 1:
                # Check if this ρ might work with the eigenvalue condition
                # Look for δ that makes ρ rational combination

                for candidate_N in [10, 20, 30, 40, 50, 60, 80, 100, 120]:
                    result = verify_revival(10, rho_candidate, delta, candidate_N)

                    if result['is_identity']:
                        # Check if this is new (not from k=5)
                        known_rhos = [(5 - np.sqrt(5))/10, (5 + np.sqrt(5))/10]
                        is_known = any(abs(rho_candidate - kr) < 1e-8 for kr in known_rhos)

                        if not is_known:
                            solutions_found.append({
                                'N': candidate_N,
                                'rho': rho_candidate,
                                'delta': delta,
                                'delta_deg': np.degrees(delta),
                                'fraction': f"{num}/{denom}"
                            })
                            print(f"\n✨ NEW k=10 SOLUTION!")
                            print(f"   N = {candidate_N}")
                            print(f"   ρ = {rho_candidate:.10f}")
                            print(f"   δ = {np.degrees(delta):.1f}° ({delta:.4f} rad)")
                            print(f"   Fraction: {num}/{denom}")
                            print(f"   ||U^{candidate_N} - I|| = {result['diff_norm']:.2e}")

    return solutions_found


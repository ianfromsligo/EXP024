def search_new_k12_revivals(max_denom=15, max_N=60):
    """
    Search for new k=12 revivals not inherited from divisors.

    For k=12, the paper's Eq. (78) becomes quite complex.
    We'll search systematically using the eigenvalue condition.
    """
    print("\n" + "=" * 80)
    print(f"SEARCHING FOR NEW k=12 REVIVALS (max_denom={max_denom}, max_N={max_N})")
    print("=" * 80)

    # Special δ values that simplify the equations for k=12
    # Since 12 is divisible by 2,3,4,6, many δ values might work
    delta_values = set()

    # From k=3: δ = 0, 2π/3, 4π/3
    delta_values.add(0)
    delta_values.add(2*np.pi/3)
    delta_values.add(4*np.pi/3)

    # From k=4: δ = 0, π/2, π, 3π/2
    delta_values.add(np.pi/2)
    delta_values.add(np.pi)
    delta_values.add(3*np.pi/2)

    # From k=6: should be same as k=3
    # From k=2: δ = 0 (already have)

    # Also try δ = 2π·p/12 for p coprime to 12
    for p in [1, 5, 7, 11]:  # coprime to 12
        delta_values.add(2*np.pi * p / 12)

    # Try δ = 2π·p/8? (since 12 and 8 share factors)
    for p in [1, 3, 5, 7]:
        delta_values.add(2*np.pi * p / 8)

    delta_list = sorted(list(delta_values))

    print(f"\nTesting {len(delta_list)} special δ values:")
    for delta in delta_list:
        print(f"  {np.degrees(delta):.0f}° ({delta:.4f} rad)")

    # Generate rational fractions for θ = 4π·m/n
    fractions = []
    for denom in range(1, max_denom + 1):
        for num in range(1, denom):
            if np.gcd(num, denom) == 1:
                fractions.append((num, denom, 4 * np.pi * num / denom))

    print(f"\nSearching through {len(fractions)} fractions...")

    new_solutions = []
    tested_pairs = 0

    # For k=12, the condition is that all ρ_l for l=0..11 are equal
    # This gives 11 independent equations

    for delta in delta_list:
        cos_delta = np.cos(delta)

        # We'll try to find consistent ρ from pairs of l values
        # l=0 and l=1 are typically most different

        for (num1, denom1, theta1) in fractions:
            # ρ from l=0 denominator: 1 - cos(δ)
            rho1 = (1 - np.cos(theta1 - delta)) / (1 - cos_delta) if abs(1 - cos_delta) > 1e-8 else 0

            if rho1 <= 0 or rho1 >= 1:
                continue

            # Now find matching fraction for l=1 denominator: 1 - cos(2π/12 + δ) = 1 - cos(π/6 + δ)
            target_for_l1 = rho1 * (1 - np.cos(np.pi/6 + delta))

            for (num2, denom2, theta2) in fractions:
                rho2_calc = 1 - np.cos(theta2 - delta)

                if abs(rho2_calc - target_for_l1) < 1e-6:
                    # Found a candidate pair
                    # Also need to check l=2,3,... but this is promising

                    # Estimate N from denominators
                    delta_frac = Fraction(delta / (2 * np.pi)).limit_denominator(max_denom * 2)
                    n_delta = delta_frac.denominator

                    N_candidate = np.lcm.reduce([denom1, denom2, n_delta * 2])

                    if N_candidate <= max_N:
                        result = verify_revival(12, rho1, delta, N_candidate)

                        if result['is_identity']:
                            # Check if this is already known
                            solution_key = (N_candidate, round(rho1, 8), round(delta, 4))

                            if solution_key not in new_solutions:
                                new_solutions.append({
                                    'N': N_candidate,
                                    'rho': rho1,
                                    'delta': delta,
                                    'delta_deg': np.degrees(delta),
                                    'frac1': f"{num1}/{denom1}",
                                    'frac2': f"{num2}/{denom2}",
                                    'delta_frac': delta_frac
                                })

                                print(f"\n✨ POTENTIAL NEW k=12 REVIVAL!")
                                print(f"   N = {N_candidate}")
                                print(f"   ρ = {rho1:.10f}")
                                print(f"   δ = {np.degrees(delta):.1f}° ({delta:.4f} rad)")
                                print(f"   δ/(2π) = {delta_frac}")
                                print(f"   Fractions: {num1}/{denom1}, {num2}/{denom2}")
                                print(f"   ||U^{N_candidate} - I|| = {result['diff_norm']:.2e}")

            tested_pairs += 1
            if tested_pairs % 1000 == 0:
                print(f"   Searched {tested_pairs} pairs, found {len(new_solutions)} candidates...")

    return new_solutions


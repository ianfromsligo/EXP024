def construct_U_k(k, rho, alpha, beta):
    """Construct quantum walk operator U_k on a cycle of k nodes."""
    C = np.array([
        [np.sqrt(rho), np.sqrt(1-rho) * np.exp(1j * alpha)],
        [np.sqrt(1-rho) * np.exp(1j * beta), -np.sqrt(rho) * np.exp(1j * (alpha + beta))]
    ], dtype=complex)

    U = np.zeros((2*k, 2*k), dtype=complex)

    for i in range(k):
        for s in [0, 1]:
            if s == 0:
                new_i = (i - 1) % k
            else:
                new_i = (i + 1) % k

            old_idx = i * 2 + s
            new_idx = new_i * 2 + s
            U[new_idx, old_idx] = 1.0

    I_k = np.eye(k)
    I_kron_C = np.kron(I_k, C)
    U = U @ I_kron_C

    return U

def verify_revival(k, rho, delta, N, tol=1e-8):
    """Verify that U_k^N = I_{2k}."""
    alpha = delta
    beta = 0.0

    U = construct_U_k(k, rho, alpha, beta)
    U_power = np.linalg.matrix_power(U, N)
    I = np.eye(2*k, dtype=complex)
    diff = np.linalg.norm(U_power - I)

    eigenvalues = np.linalg.eigvals(U)
    max_eig_error = max(abs(ev**N - 1) for ev in eigenvalues)

    return {
        'diff_norm': diff,
        'is_identity': diff < tol,
        'max_eig_error': max_eig_error
    }


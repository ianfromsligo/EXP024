    print("TESTING k=20 PREDICTIONS")
    print("=" * 80)

    # Test inheritance from k=5 (should work for k=10, but not for k=20)
    rho_k5 = [(5 - np.sqrt(5))/10, (5 + np.sqrt(5))/10]
    delta_k5 = [0, 2*np.pi/5, 4*np.pi/5, 6*np.pi/5, 8*np.pi/5]

    print("\nTesting inheritance from k=5 (expected: NO):")
    inheritance_found = False

    for rho in rho_k5:
        for delta in delta_k5:
            for N in [20, 40, 60, 80, 100, 120]:
                result = verify_revival(20, rho, delta, N)
                if result['is_identity']:
                    print(f"  ✗ UNEXPECTED! N={N}, ρ={rho:.8f}, δ={np.degrees(delta):.0f}°")
                    inheritance_found = True
                    break
            else:
                pass  # Expected no revival

    if not inheritance_found:
        print("  ✓ No inheritance from k=5 (as expected)")

    # Test inheritance from k=10 (should work for k=20 if doubling applied twice, but likely not)
    rho_k10 = [(5 - np.sqrt(5))/10, (5 + np.sqrt(5))/10]

    print("\nTesting inheritance from k=10 (expected: NO):")
    for rho in rho_k10:
        for delta in delta_k5:
            for N in [20, 40, 60, 80, 100, 120]:
                result = verify_revival(20, rho, delta, N)
                if result['is_identity']:
                    print(f"  ✗ UNEXPECTED! N={N}, ρ={rho:.8f}, δ={np.degrees(delta):.0f}°")
                    inheritance_found = True
                    break
            else:
                pass

    if not inheritance_found:
        print("  ✓ No inheritance from k=10 (as expected - doubling is one-step only)")

    # Test k=4 solutions (since 20 is multiple of 4)
    k4_rhos = [1/2, 1/4, 3/4, (2 - np.sqrt(3))/2]
    k4_deltas = [0, np.pi/2, np.pi, 3*np.pi/2]

    print("\nTesting inheritance from k=4 (expected: NO):")
    for rho in k4_rhos:
        for delta in k4_deltas:
            for N in [10, 20, 30, 40, 50, 60]:
                result = verify_revival(20, rho, delta, N)
                if result['is_identity']:
                    print(f"  ✗ UNEXPECTED! N={N}, ρ={rho:.6f}, δ={np.degrees(delta):.0f}°")
                    inheritance_found = True
                    break
            else:
                pass

    if not inheritance_found:
        print("  ✓ No inheritance from k=4")

    # Systematic search for any revival in k=20
    print("\nSystematic search for any revival (0<ρ<1, N≤120):")

    # Special δ values that might work
    delta_candidates = [0, np.pi/6, np.pi/4, np.pi/3, np.pi/2, 2*np.pi/3,
                        3*np.pi/4, 5*np.pi/6, np.pi, 7*np.pi/6, 5*np.pi/4,
                        4*np.pi/3, 3*np.pi/2, 5*np.pi/3, 7*np.pi/4, 11*np.pi/6]

    fractions = []
    for denom in range(1, 15):
        for num in range(1, denom):
            if np.gcd(num, denom) == 1:
                fractions.append((num, denom, 4 * np.pi * num / denom))

    found_any = False

    for delta in delta_candidates:
        cos_delta = np.cos(delta)
        if abs(1 - cos_delta) < 1e-8:
            continue

        for num, denom, theta in fractions:
            rho_candidate = (1 - np.cos(theta - delta)) / (1 - cos_delta)

            if 0.01 < rho_candidate < 0.99:  # Nontrivial range
                delta_frac = Fraction(delta / (2 * np.pi)).limit_denominator(20)
                n_delta = delta_frac.denominator
                N_candidate = np.lcm.reduce([denom, n_delta * 2, 10])

                if N_candidate <= 120:
                    result = verify_revival(20, rho_candidate, delta, N_candidate)
                    if result['is_identity']:
                        print(f"\n  ✗ UNEXPECTED REVIVAL FOUND!")
                        print(f"     N={N_candidate}, ρ={rho_candidate:.10f}, δ={np.degrees(delta):.1f}°")
                        print(f"     Fraction: {num}/{denom}")
                        found_any = True

    if not found_any:
        print("\n  ✓ CONFIRMED: No nontrivial revivals found for k=20")
        print("    Only ρ=0,1 trivial solutions exist")

    return not found_any

